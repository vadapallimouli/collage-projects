"""
tests/test_multiple_trajectory_visualizer.py

Visualize MANY candidate trajectories generated by
the actual obstacle-aware planner.

Pipeline:

MπNets
  ↓
DIRECT PyBullet
  ↓
Panda + obstacles
  ↓
Generate collision-free goal
  ↓
Generate 10 candidate trajectories
  ↓
Validate candidates
  ↓
GUI PyBullet
  ↓
Display all candidates
  ↓
Highlight selected candidate
  ↓
Animate selected candidate
"""

from __future__ import annotations

import pickle
import sys
import time
from pathlib import Path

import numpy as np
import pybullet as p
import pybullet_data


# ================================================================
# PROJECT PATH
# ================================================================

PROJECT_ROOT = (
    Path(__file__).resolve().parents[1]
)

if str(PROJECT_ROOT) not in sys.path:

    sys.path.insert(
        0,
        str(PROJECT_ROOT),
    )


# ================================================================
# IMPORTS
# ================================================================

from robot.panda_robot import PandaRobot

from environment.environment import Environment

from analysis.collision_checker import CollisionChecker

from planning.trajectory_generator import (
    TrajectoryGenerator,
)

from planning.goal_configuration import (
    GoalConfigurationGenerator,
)

from planning.obstacle_aware_planner import (
    ObstacleAwarePlanner,
)

from visualization.robot_visualizer import (
    RobotVisualizer,
)


# ================================================================
# DATASET
# ================================================================

DATASET_PATH = (
    PROJECT_ROOT
    / "data"
    / "mpinets"
    / "both_solvable_problems.pkl"
)

ENVIRONMENT_NAME = "tabletop"
PROBLEM_SET_NAME = "task_oriented"
PROBLEM_INDEX = 0


# ================================================================
# PLANNER SETTINGS
# ================================================================

NUM_CANDIDATES = 10

PLANNER_SAMPLES = 700

PLANNER_K_NEIGHBORS = 15

PLANNER_EDGE_POINTS = 25


# ================================================================
# LOAD PROBLEM
# ================================================================

def load_problem():

    print(
        "Loading MπNets dataset..."
    )

    with open(
        DATASET_PATH,
        "rb",
    ) as file:

        dataset = pickle.load(
            file
        )

    problem = (
        dataset
        [ENVIRONMENT_NAME]
        [PROBLEM_SET_NAME]
        [PROBLEM_INDEX]
    )

    print(
        f"Environment : "
        f"{ENVIRONMENT_NAME}"
    )

    print(
        f"Problem set : "
        f"{PROBLEM_SET_NAME}"
    )

    print(
        f"Problem      : "
        f"{PROBLEM_INDEX}"
    )

    return problem


# ================================================================
# CREATE SIMULATION
# ================================================================

def create_simulation(
    mode,
):

    physics_client = p.connect(
        mode
    )

    if physics_client < 0:

        raise RuntimeError(
            "Could not connect to PyBullet."
        )

    p.setAdditionalSearchPath(
        pybullet_data.getDataPath()
    )

    p.setGravity(
        0,
        0,
        -9.81,
    )

    p.loadURDF(
        "plane.urdf"
    )

    robot_id = p.loadURDF(
        "franka_panda/panda.urdf",
        useFixedBase=True,
    )

    panda_robot = PandaRobot(
        robot_id
    )

    return (
        physics_client,
        panda_robot,
    )


# ================================================================
# FIND GOAL
# ================================================================

def find_collision_free_goal(
    panda_robot,
    environment,
    collision_checker,
    physics_client,
):

    print(
        "Generating goal configurations..."
    )

    goal_generator = (
        GoalConfigurationGenerator(
            panda_robot=panda_robot,
            environment=environment,
            target_position=environment.target_position,
            target_half_extents=environment.target_half_extents,
            client_id=physics_client,
        )
    )

    solutions = (
        goal_generator.solve_multiple(
            num_solutions=20,
            num_rest_poses=20,
            seed=42,
        )
    )

    print(
        f"IK solutions generated: "
        f"{len(solutions)}"
    )

    for solution in solutions:

        configuration = np.asarray(
            solution["configuration"],
            dtype=float,
        )

        result = (
            collision_checker.check_configuration(
                configuration
            )
        )

        if not result["collision"]:

            print(
                "Collision-free goal found."
            )

            return configuration

    raise RuntimeError(
        "Could not find collision-free goal."
    )


# ================================================================
# GENERATE CANDIDATES
# ================================================================

def generate_candidates():

    print()
    print(
        "=" * 70
    )

    print(
        "PHASE 1: CANDIDATE GENERATION"
    )

    print(
        "=" * 70
    )

    physics_client = None

    try:

        (
            physics_client,
            panda_robot,
        ) = create_simulation(
            p.DIRECT
        )

        print()
        print(
            "PyBullet mode: DIRECT"
        )

        problem = load_problem()

        environment = (
            Environment.from_mpinets_problem(
                problem
            )
        )

        obstacle_ids = (
            environment.create_pybullet_obstacles(
                client_id=physics_client
            )
        )

        print()
        print(
            f"Obstacles created: "
            f"{len(obstacle_ids)}"
        )

        collision_checker = CollisionChecker(
            panda_robot=panda_robot,
            environment=environment,
            client_id=physics_client,
        )

        trajectory_generator = (
            TrajectoryGenerator(
                panda_robot
            )
        )

        start = np.asarray(
            problem.q0,
            dtype=float,
        )

        start_result = (
            collision_checker.check_configuration(
                start
            )
        )

        print()
        print(
            "Start collision: "
            f"{start_result['collision']}"
        )

        if start_result["collision"]:

            raise RuntimeError(
                "Start configuration is in collision."
            )

        goal = find_collision_free_goal(
            panda_robot=panda_robot,
            environment=environment,
            collision_checker=collision_checker,
            physics_client=physics_client,
        )

        planner = ObstacleAwarePlanner(
            panda_robot=panda_robot,
            collision_checker=collision_checker,
            trajectory_generator=trajectory_generator,
            num_samples=PLANNER_SAMPLES,
            k_neighbors=PLANNER_K_NEIGHBORS,
            edge_points=PLANNER_EDGE_POINTS,
            seed=42,
        )

        print()
        print(
            f"Generating {NUM_CANDIDATES} "
            "candidate trajectories..."
        )

        results = (
            planner.plan_multiple(
                start,
                goal,
                num_candidates=NUM_CANDIDATES,
            )
        )

        candidates = []

        for result in results:

            trajectory = result.get(
                "trajectory"
            )

            if trajectory is None:
                continue

            trajectory = np.asarray(
                trajectory,
                dtype=float,
            )

            if trajectory.ndim != 2:
                continue

            if trajectory.shape[1] != 7:
                continue

            validation = (
                collision_checker.check_trajectory(
                    trajectory
                )
            )

            if not validation[
                "collision_free"
            ]:

                continue

            candidates.append(
                trajectory
            )

        print()
        print(
            f"Valid candidate trajectories: "
            f"{len(candidates)}"
        )

        if len(candidates) < 2:

            raise RuntimeError(
                "Need at least two valid candidate "
                "trajectories for visualization."
            )

        for index, trajectory in enumerate(
            candidates
        ):

            print(
                f"  Candidate {index + 1}: "
                f"{trajectory.shape}"
            )

        return (
            candidates,
            problem,
        )

    finally:

        if (
            physics_client is not None
            and p.isConnected(
                physics_client
            )
        ):

            p.disconnect(
                physics_client
            )

            print()
            print(
                "DIRECT planning server closed."
            )


# ================================================================
# GUI VISUALIZATION
# ================================================================

def visualize_candidates(
    candidates,
    problem,
):

    print()
    print(
        "=" * 70
    )

    print(
        "PHASE 2: MULTIPLE TRAJECTORY VISUALIZATION"
    )

    print(
        "=" * 70
    )

    physics_client = None

    try:

        (
            physics_client,
            panda_robot,
        ) = create_simulation(
            p.GUI
        )

        print()
        print(
            "PyBullet mode: GUI"
        )

        time.sleep(
            1.0
        )

        if not p.isConnected(
            physics_client
        ):

            raise RuntimeError(
                "GUI connection failed."
            )

        environment = (
            Environment.from_mpinets_problem(
                problem
            )
        )

        obstacle_ids = (
            environment.create_pybullet_obstacles(
                client_id=physics_client
            )
        )

        print(
            f"Obstacles created: "
            f"{len(obstacle_ids)}"
        )

        visualizer = RobotVisualizer(
            panda_robot=panda_robot,
            environment=environment,
            client_id=physics_client,
            trajectory_dt=0.08,
            interpolation_steps=3,
            max_visual_points=60,
        )

        visualizer.set_camera(
            distance=1.8,
            yaw=45.0,
            pitch=-35.0,
            target=environment.target_position,
        )

        # --------------------------------------------------------
        # Use first candidate as the selected trajectory
        # for this visualization test.
        # --------------------------------------------------------

        selected_index = 0

        selected = candidates[
            selected_index
        ]

        # --------------------------------------------------------
        # Put robot at start.
        # --------------------------------------------------------

        visualizer.set_robot_configuration(
            selected[0]
        )

        p.stepSimulation()

        # --------------------------------------------------------
        # Mark start and goal.
        # --------------------------------------------------------

        visualizer.mark_start_and_goal(
            selected
        )

        # --------------------------------------------------------
        # Draw all candidate trajectories.
        # --------------------------------------------------------

        visualizer.draw_multiple_trajectories(
            candidates,
            line_width=1.5,
            line_color=[
                0.2,
                0.7,
                1.0,
            ],
            selected_index=selected_index,
            selected_color=[
                1.0,
                0.8,
                0.0,
            ],
            selected_line_width=4.0,
        )

        p.stepSimulation()

        print()
        print(
            "=" * 70
        )

        print(
            "CANDIDATE VISUALIZATION"
        )

        print(
            "=" * 70
        )

        print()
        print(
            f"Candidates displayed: "
            f"{len(candidates)}"
        )

        print(
            f"Selected candidate: "
            f"{selected_index + 1}"
        )

        print()
        print(
            "Blue paths  = candidate trajectories"
        )

        print(
            "Yellow path = selected trajectory"
        )

        print()
        print(
            "The robot will now animate the "
            "selected trajectory."
        )

        time.sleep(
            2.0
        )

        # --------------------------------------------------------
        # Animate selected candidate.
        # --------------------------------------------------------

        visualizer.animate_trajectory(
            selected,
            loop=False,
            hold_at_end=2.0,
            interpolation_steps=3,
        )

        print()
        print(
            "[PASS] Multiple candidate paths displayed."
        )

        print(
            "[PASS] Selected trajectory highlighted."
        )

        print(
            "[PASS] Selected trajectory animated."
        )

        print()
        print(
            "Close the PyBullet window to finish."
        )

        visualizer.wait_until_closed()

    finally:

        if (
            physics_client is not None
            and p.isConnected(
                physics_client
            )
        ):

            p.disconnect(
                physics_client
            )


